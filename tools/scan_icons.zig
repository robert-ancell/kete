//! Scans Zig source files for `IconName` references and generates a subset
//! `names.zig` containing only the icons actually used.
//!
//! Three patterns are recognised (all unambiguous about the type):
//!
//!   1. `IconName.name` — explicit type qualification.
//!   2. `.field = <expr>` — enum inference when `field` is a known `IconName`-
//!      typed field: `icon`, `leading_icon`, `trailing_icon`.
//!   3. `name: ?IconName = <expr>` — a declaration of type `IconName` (or
//!      `?IconName`, however qualified).
//!
//!   4. `[_]IconName{ .name, ... }` — a list of them.
//!
//! In 2 and 3 every `.name` in the expression counts, so choices such as
//! `if (on) .visibility_off else .visibility` or `x orelse .close` are found.
//!
//! For icons chosen dynamically (e.g. stored in a variable or selected at
//! runtime), add a no-op reference anywhere in your source:
//!
//!     comptime { _ = &[_]kete.IconName{ .cloud, .download }; }
//!
//!     scan_icons <codepoints_file> <out_names.zig> <dir1> [<dir2> ...]

const std = @import("std");

/// `IconName`-typed fields in kete's widget API.
const icon_fields = [_][]const u8{ "icon", "leading_icon", "trailing_icon" };

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 4) {
        std.debug.print(
            "usage: scan_icons <codepoints_file> <out_names.zig> <dir1> [<dir2> ...]\n",
            .{},
        );
        std.process.exit(2);
    }
    const io = init.io;
    const cwd = std.Io.Dir.cwd();

    // Build set of valid icon names from the codepoints file ("name hex\n").
    const cp_data = try cwd.readFileAlloc(io, args[1], arena, .limited(1 << 20));
    var valid: std.StringHashMapUnmanaged(void) = .empty;
    {
        var lines = std.mem.tokenizeAny(u8, cp_data, "\r\n");
        while (lines.next()) |line| {
            var fields = std.mem.tokenizeScalar(u8, line, ' ');
            const name = fields.next() orelse continue;
            if (fields.next() != null) try valid.put(arena, name, {});
        }
    }

    // Scan source directories.
    var found: std.StringHashMapUnmanaged(void) = .empty;
    for (args[3..]) |dir_path| {
        var dir = cwd.openDir(io, dir_path, .{ .iterate = true }) catch |e| {
            std.debug.print("scan_icons: cannot open '{s}': {}\n", .{ dir_path, e });
            std.process.exit(1);
        };
        defer dir.close(io);
        try scanDir(io, dir, arena, &valid, &found);
    }

    // Sort found icon names (names.zig is alphabetical).
    const sorted = try arena.alloc([]const u8, found.count());
    {
        var it = found.keyIterator();
        for (sorted) |*s| s.* = it.next().?.*;
    }
    std.mem.sort([]const u8, sorted, {}, struct {
        fn lt(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lt);

    // Write names.zig.
    var buf: std.ArrayList(u8) = .empty;
    try buf.appendSlice(arena,
        \\//! Generated by tools/scan_icons.zig — only the icons referenced in this
        \\//! project's source. To include dynamically-chosen icons add a no-op, e.g.:
        \\//!     comptime { _ = &[_]kete.IconName{ .folder, .settings }; }
        \\
        \\const std = @import("std");
        \\
        \\/// A Material icon used by this project.
        \\pub const IconName = enum {
        \\
    );
    for (sorted) |name| {
        if (needsQuote(name)) {
            try buf.print(arena, "    @\"{s}\",\n", .{name});
        } else {
            try buf.print(arena, "    {s},\n", .{name});
        }
    }
    try buf.appendSlice(arena,
        \\
        \\    /// The icon with this name (ignoring surrounding whitespace), if any.
        \\    pub fn fromName(name: []const u8) ?@This() {
        \\        @setEvalBranchQuota(100_000);
        \\        return std.meta.stringToEnum(@This(), std.mem.trim(u8, name, " \t\r\n"));
        \\    }
        \\};
        \\
    );
    const out = try cwd.createFile(io, args[2], .{});
    defer out.close(io);
    try out.writeStreamingAll(io, buf.items);

    std.debug.print("scan_icons: {d} icon(s) found\n", .{sorted.len});
}

fn scanDir(
    io: std.Io,
    dir: std.Io.Dir,
    arena: std.mem.Allocator,
    valid: *const std.StringHashMapUnmanaged(void),
    found: *std.StringHashMapUnmanaged(void),
) !void {
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        switch (entry.kind) {
            .file => {
                if (!std.mem.endsWith(u8, entry.name, ".zig")) continue;
                const src = dir.readFileAlloc(io, entry.name, arena, .limited(10 << 20)) catch continue;
                scanFile(src, valid, found, arena);
            },
            .directory => {
                if (entry.name[0] == '.') continue; // skip .zig-cache, etc.
                var sub = dir.openDir(io, entry.name, .{ .iterate = true }) catch continue;
                defer sub.close(io);
                try scanDir(io, sub, arena, valid, found);
            },
            else => {},
        }
    }
}

/// Scans one source file for icon name references.
fn scanFile(
    src: []const u8,
    valid: *const std.StringHashMapUnmanaged(void),
    found: *std.StringHashMapUnmanaged(void),
    arena: std.mem.Allocator,
) void {
    var i: usize = 0;
    while (i < src.len) {
        // Pattern 1: `IconName.name` — unambiguous, always an IconName.
        if (std.mem.startsWith(u8, src[i..], "IconName.")) {
            i += "IconName.".len;
            collectName(src, &i, valid, found, arena);
            continue;
        }
        // Pattern 3: `: ?IconName = <expr>`.
        if (std.mem.startsWith(u8, src[i..], "IconName") and (i == 0 or !isIdentChar(src[i - 1]))) {
            var j = i + "IconName".len;
            if (j < src.len and isIdentChar(src[j])) {
                i = j;
                continue;
            }
            while (j < src.len and isSpace(src[j])) j += 1;
            // Pattern 4: a list, `[_]IconName{ .a, .b }`.
            if (j < src.len and src[j] == '{') {
                j += 1;
                while (true) {
                    j = collectExpr(src, j, valid, found, arena);
                    if (j >= src.len or src[j] != ',') break;
                    j += 1;
                }
                i = j;
                continue;
            }
            if (j < src.len and src[j] == '=' and !(j + 1 < src.len and src[j + 1] == '=')) {
                i = collectExpr(src, j + 1, valid, found, arena);
                continue;
            }
            i = j;
            continue;
        }
        // Pattern 2: `.field = .name` for known IconName-typed fields.
        if (src[i] == '.') {
            if (tryFieldAssign(src, i, valid, found, arena)) |next| {
                i = next;
                continue;
            }
        }
        i += 1;
    }
}

/// Tries to match `.field = .name` at position `i` (where `src[i] == '.'`).
/// Returns the position after the name on success, null on no match.
fn tryFieldAssign(
    src: []const u8,
    i: usize,
    valid: *const std.StringHashMapUnmanaged(void),
    found: *std.StringHashMapUnmanaged(void),
    arena: std.mem.Allocator,
) ?usize {
    for (icon_fields) |field| {
        // Check `.field` starts at i.
        const field_end = i + 1 + field.len;
        if (field_end > src.len) continue;
        if (!std.mem.eql(u8, src[i + 1 .. field_end], field)) continue;
        // Ensure the field name isn't part of a longer identifier (e.g. `.icon_button`).
        if (field_end < src.len and isIdentChar(src[field_end])) continue;
        // Skip whitespace, match '=', skip whitespace, match '.'.
        var j = field_end;
        while (j < src.len and isSpace(src[j])) j += 1;
        if (j >= src.len or src[j] != '=') continue;
        j += 1;
        // Don't match `==`.
        if (j < src.len and src[j] == '=') continue;
        return collectExpr(src, j, valid, found, arena);
    }
    return null;
}

/// Records every `.name` in the expression starting at `i` (up to a `,` or
/// `;`, or a bracket closing one opened before it), and returns the position
/// after it.
fn collectExpr(
    src: []const u8,
    start: usize,
    valid: *const std.StringHashMapUnmanaged(void),
    found: *std.StringHashMapUnmanaged(void),
    arena: std.mem.Allocator,
) usize {
    var i = start;
    var depth: usize = 0;
    while (i < src.len) {
        switch (src[i]) {
            '(', '[', '{' => depth += 1,
            ')', ']', '}' => {
                if (depth == 0) return i;
                depth -= 1;
            },
            ',', ';' => if (depth == 0) return i,
            '"' => {
                // Skip strings (a `.` in one is not an enum literal).
                i += 1;
                while (i < src.len and src[i] != '"' and src[i] != '\n') : (i += 1) {
                    if (src[i] == '\\') i += 1;
                }
            },
            '.' => if (i + 1 < src.len and (isIdentChar(src[i + 1]) or src[i + 1] == '@') and
                (i == 0 or !isIdentChar(src[i - 1]) and src[i - 1] != ')' and src[i - 1] != ']'))
            {
                i += 1;
                collectName(src, &i, valid, found, arena);
                continue;
            },
            else => {},
        }
        i += 1;
    }
    return i;
}

/// Reads an icon name (plain or `@"quoted"`) at `i`, records it if valid.
fn collectName(
    src: []const u8,
    i: *usize,
    valid: *const std.StringHashMapUnmanaged(void),
    found: *std.StringHashMapUnmanaged(void),
    arena: std.mem.Allocator,
) void {
    if (i.* >= src.len) return;
    // @"quoted" form (e.g. .@"error", .@"10k").
    if (src[i.*] == '@' and i.* + 1 < src.len and src[i.* + 1] == '"') {
        i.* += 2;
        const start = i.*;
        while (i.* < src.len and src[i.*] != '"') i.* += 1;
        const name = src[start..i.*];
        if (i.* < src.len) i.* += 1; // skip closing '"'
        if (valid.contains(name)) found.put(arena, name, {}) catch {};
        return;
    }
    // Plain identifier.
    const start = i.*;
    while (i.* < src.len and isIdentChar(src[i.*])) i.* += 1;
    const name = src[start..i.*];
    if (valid.contains(name)) found.put(arena, name, {}) catch {};
}

fn isIdentChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_';
}

fn isSpace(c: u8) bool {
    return c == ' ' or c == '\t' or c == '\n' or c == '\r';
}

/// Whether the icon name needs `@"..."` quoting in Zig source.
fn needsQuote(name: []const u8) bool {
    if (name.len > 0 and std.ascii.isDigit(name[0])) return true;
    if (std.zig.Token.getKeyword(name) != null) return true;
    return false;
}

test "icons are found in each pattern, and only icons" {
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var valid: std.StringHashMapUnmanaged(void) = .empty;
    for ([_][]const u8{ "add", "close", "menu", "home", "visibility", "visibility_off", "arrow_right", "crop_square", "filter_none", "cloud", "download", "10k", "search", "unused" }) |n| try valid.put(arena, n, {});
    var found: std.StringHashMapUnmanaged(void) = .empty;
    scanFile(
        \\const a = IconName.add;
        \\const b = Button{ .icon = .close, .label = "x.home" };
        \\const c = Item{ .trailing_icon = if (it.sub) .arrow_right else it.trailing_icon };
        \\const d: ?icons.IconName = if (st.revealed) .visibility_off else .visibility;
        \\const e = Bar{ .icon = if (maximized) .filter_none else .crop_square, .size = .search };
        \\comptime { _ = &[_]kete.IconName{ .cloud, .download, .@"10k" }; }
        \\const f = x.menu; const g = .home; if (s == .unused) {}
    , &valid, &found, arena);
    var names: std.ArrayList([]const u8) = .empty;
    var it = found.keyIterator();
    while (it.next()) |k| try names.append(arena, k.*);
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lt(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lt);
    const want = [_][]const u8{ "10k", "add", "arrow_right", "close", "cloud", "crop_square", "download", "filter_none", "visibility", "visibility_off" };
    try std.testing.expectEqual(want.len, names.items.len);
    for (want, names.items) |w, n| try std.testing.expectEqualStrings(w, n);
}
